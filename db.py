"""저장소 접근 레이어.

페이지 코드는 SQL을 직접 실행하지 않고 반드시 `get_storage()`가 돌려주는 객체의
메서드만 사용한다.

저장소는 두 가지다.
- SQLite (기본): 로컬 개발용. `data/gym.db`, 또는 GYM_DB_PATH 환경변수의 파일.
- PostgreSQL (Supabase): DATABASE_URL 환경변수(또는 같은 이름의 Streamlit secret)가 있으면 사용.
  Streamlit Community Cloud는 재시작 때 로컬 파일을 지우므로 배포에서는 반드시 이쪽을 쓴다.

SQL은 두 DB에서 똑같이 동작하는 문법만 쓴다 (`?` 플레이스홀더, ON CONFLICT, RETURNING).
DB마다 다른 부분(DDL, 연결, 스키마 버전 저장 위치, 무결성 오류 종류)만 백엔드 클래스가 맡는다.
"""

