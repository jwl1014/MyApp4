class SQLiteBackend:
    def __init__(self, db_path: str | Path):
        self.db_path = Path(db_path)
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self.integrity_error: type[Exception] = sqlite3.IntegrityError

    @contextmanager
    def connect(self) -> Iterator[sqlite3.Connection]:
        # Streamlit은 스크립트를 여러 스레드에서 실행하므로 호출마다 연결을 새로 연다.
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def create_schema(self, conn) -> None:
        conn.executescript(SQLITE_SCHEMA)

    def get_version(self, conn) -> int:
        return conn.execute("PRAGMA user_version").fetchone()[0]

    def set_version(self, conn, version: int) -> None:
        conn.execute(f"PRAGMA user_version = {int(version)}")

    def after_seed(self, conn) -> None:
        pass

    def is_unique_violation(self, e: Exception) -> bool:
        return "UNIQUE constraint failed" in str(e)


class _PgConnection:
    """psycopg 연결을 sqlite3처럼 `?` 플레이스홀더로 쓰게 해 주는 얇은 래퍼."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params: Iterable[Any] = ()):
        # 이 모듈의 SQL에는 리터럴 '?' 나 '%'가 없으므로 단순 치환으로 충분하다.
        return self._conn.execute(sql.replace("?", "%s"), tuple(params))


class PostgresBackend:
    def __init__(self, url: str):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        self._psycopg = psycopg
        self.integrity_error = psycopg.IntegrityError
        # Supabase 연결 풀러(pgbouncer, transaction 모드)는 prepared statement를 지원하지 않는다.
        self._pool = ConnectionPool(
            url,
            min_size=1,
            max_size=5,
            kwargs={"row_factory": dict_row, "prepare_threshold": None},
            open=True,
        )

    @contextmanager
    def connect(self) -> Iterator[_PgConnection]:
        # 블록을 정상 종료하면 커밋, 예외가 나면 롤백된다.
        with self._pool.connection() as conn:
            yield _PgConnection(conn)

    def create_schema(self, conn) -> None:
        # 앱 인스턴스 여러 개가 동시에 시작해도 스키마 생성·시드가 겹치지 않게 잠근다.
        conn.execute("SELECT pg_advisory_xact_lock(7420151)")
        for statement in POSTGRES_SCHEMA.split(";"):
            if statement.strip():
                conn.execute(statement)

    def get_version(self, conn) -> int:
        row = conn.execute("SELECT value FROM app_meta WHERE key = 'schema_version'").fetchone()
        return int(row["value"]) if row else 0

    def set_version(self, conn, version: int) -> None:
        conn.execute(
            """INSERT INTO app_meta (key, value) VALUES ('schema_version', ?)
               ON CONFLICT (key) DO UPDATE SET value = excluded.value""",
            (str(version),),
        )

    def after_seed(self, conn) -> None:
        # 시드는 id를 직접 넣으므로 IDENTITY 시퀀스를 최댓값 뒤로 옮겨야 다음 INSERT가 충돌하지 않는다.
        for table in ("body_parts", "exercises", "favorites"):
            conn.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"(SELECT COALESCE(MAX(id), 0) + 1 FROM {table}), false)"
            )

    def is_unique_violation(self, e: Exception) -> bool:
        return isinstance(e, self._psycopg.errors.UniqueViolation)


# ===================================================================== 저장소

class Storage:
    def __init__(self, backend: SQLiteBackend | PostgresBackend, seed_path: str | Path = SEED_PATH):
        self.backend = backend
        self.seed_path = Path(seed_path)
        self._initialize()

    def _connect(self):
        return self.backend.connect()

    # ---------------------------------------------------------------- 초기화

    def _initialize(self) -> None:
        with self._connect() as conn:
            self.backend.create_schema(conn)
            if self.backend.get_version(conn) < SCHEMA_VERSION:
                self._seed(conn)
                self.backend.after_seed(conn)
                self.backend.set_version(conn, SCHEMA_VERSION)

    def _seed(self, conn) -> None:
        """최초 1회만 실행된다. 이후 사용자가 즐겨찾기를 지워도 다시 채우지 않는다."""
        seed = json.loads(self.seed_path.read_text(encoding="utf-8"))

        for order, name in enumerate(seed["body_parts"]):
            conn.execute(
                "INSERT INTO body_parts (name, sort_order) VALUES (?, ?) ON CONFLICT DO NOTHING",
                (name, order),
            )
        part_ids = {r["name"]: r["id"] for r in conn.execute("SELECT id, name FROM body_parts")}

        for ex in seed["exercises"]:
            conn.execute(
                """INSERT INTO exercises
                   (id, name, body_part_id, image_path, muscle_image_path,
                    primary_muscles, secondary_muscles, tips, mistakes, video_url)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                   ON CONFLICT DO NOTHING""",
                (
                    ex["id"],
                    ex["name"],
                    part_ids[ex["body_part"]],
                    ex.get("image_path"),
                    ex.get("muscle_image_path"),
                    ex.get("primary_muscles", ""),
                    ex.get("secondary_muscles", ""),
                    json.dumps(ex.get("tips", []), ensure_ascii=False),
                    json.dumps(ex.get("mistakes", []), ensure_ascii=False),
                    ex.get("video_url"),
                ),
            )

        order = 0
        for part, names in seed["favorites"].items():
            for name in names:
                row = conn.execute(
                    "SELECT id FROM exercises WHERE body_part_id = ? AND name = ?",
                    (part_ids[part], name),
                ).fetchone()
                conn.execute(
                    "INSERT INTO favorites (exercise_id, sort_order) VALUES (?, ?) ON CONFLICT DO NOTHING",
                    (row["id"], order),
                )
                order += 1

    # ------------------------------------------------------------ 운동 부위

    def list_body_parts(self) -> list[BodyPart]:
        with self._connect() as conn:
            rows = conn.execute("SELECT id, name FROM body_parts ORDER BY sort_order, id")
            return [BodyPart(r["id"], r["name"]) for r in rows]

    # ------------------------------------------------------------ 운동 방법

    def list_exercises(self, body_part_id: int | None = None) -> list[Exercise]:
        sql = EXERCISE_SELECT
        params: tuple = ()
        if body_part_id is not None:
            sql += " WHERE e.body_part_id = ?"
            params = (body_part_id,)
        sql += " ORDER BY b.sort_order, e.id"
        with self._connect() as conn:
            return [_to_exercise(r) for r in conn.execute(sql, params)]

    def get_exercise(self, exercise_id: int) -> Exercise | None:
        with self._connect() as conn:
            row = conn.execute(EXERCISE_SELECT + " WHERE e.id = ?", (exercise_id,)).fetchone()
            return _to_exercise(row) if row else None

    def _require_body_part(self, conn, body_part_id: int) -> None:
        if conn.execute("SELECT 1 FROM body_parts WHERE id = ?", (body_part_id,)).fetchone() is None:
            raise ValueError("존재하지 않는 부위입니다.")

    def add_exercise(
        self,
        name: str,
        body_part_id: int,
        *,
        primary_muscles: str = "",
        secondary_muscles: str = "",
        tips: list[str] | None = None,
        mistakes: list[str] | None = None,
        image_path: str | None = None,
        muscle_image_path: str | None = None,
        video_url: str | None = None,
    ) -> int:
        name = _clean_name(name)
        with self._connect() as conn:
            self._require_body_part(conn, body_part_id)
            row = conn.execute(
                """INSERT INTO exercises
                   (name, body_part_id, image_path, muscle_image_path,
                    primary_muscles, secondary_muscles, tips, mistakes, video_url)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                   ON CONFLICT (body_part_id, name) DO NOTHING
                   RETURNING id""",
                (
                    name,
                    body_part_id,
                    image_path,
                    muscle_image_path,
                    primary_muscles,
                    secondary_muscles,
                    json.dumps(tips or [], ensure_ascii=False),
                    json.dumps(mistakes or [], ensure_ascii=False),
                    video_url,
                ),
            ).fetchone()
            if row is None:
                raise ValueError(f"이미 등록된 운동입니다: {name}")
            new_id = row["id"]
            # 사진 경로를 지정하지 않으면 assets/images/{id}_form.png 규칙을 따른다.
            conn.execute(
                """UPDATE exercises
                   SET image_path = COALESCE(image_path, ?),
                       muscle_image_path = COALESCE(muscle_image_path, ?)
                   WHERE id = ?""",
                (f"assets/images/{new_id}_form.png", f"assets/images/{new_id}_muscle.png", new_id),
            )
            return new_id

    _EXERCISE_FIELDS = {
        "name", "body_part_id", "image_path", "muscle_image_path",
        "primary_muscles", "secondary_muscles", "tips", "mistakes", "video_url",
    }

    def update_exercise(self, exercise_id: int, **fields) -> None:
        unknown = set(fields) - self._EXERCISE_FIELDS
        if unknown:
            raise ValueError(f"알 수 없는 필드: {', '.join(sorted(unknown))}")
        if not fields:
            return
        if "name" in fields:
            fields["name"] = _clean_name(fields["name"])
        for key in ("tips", "mistakes"):
            if key in fields:
                fields[key] = json.dumps(fields[key] or [], ensure_ascii=False)
        # 컬럼명은 화이트리스트로 검증했으므로 문자열 조합이 안전하다.
        assignments = ", ".join(f"{k} = ?" for k in fields)
        with self._connect() as conn:
            if "body_part_id" in fields:
                self._require_body_part(conn, fields["body_part_id"])
            try:
                conn.execute(
                    f"UPDATE exercises SET {assignments} WHERE id = ?",
                    (*fields.values(), exercise_id),
                )
            except self.backend.integrity_error as e:
                if self.backend.is_unique_violation(e):
                    raise ValueError("같은 부위에 같은 이름의 운동이 이미 있습니다.") from e
                raise ValueError("운동 정보를 저장하지 못했어요. 입력값을 확인해 주세요.") from e

    # ------------------------------------------------------------ 운동 사진

    def set_exercise_image(self, exercise_id: int, kind: str, mime: str, data: bytes) -> None:
        if kind not in IMAGE_KINDS:
            raise ValueError(f"알 수 없는 사진 종류: {kind}")
        with self._connect() as conn:
            conn.execute(
                """INSERT INTO exercise_images (exercise_id, kind, mime, data) VALUES (?, ?, ?, ?)
                   ON CONFLICT (exercise_id, kind) DO UPDATE SET mime = excluded.mime, data = excluded.data""",
                (exercise_id, kind, mime, data),
            )

    def delete_exercise_image(self, exercise_id: int, kind: str) -> None:
        with self._connect() as conn:
            conn.execute(
                "DELETE FROM exercise_images WHERE exercise_id = ? AND kind = ?", (exercise_id, kind)
            )

    def get_exercise_image(self, exercise_id: int, kind: str) -> tuple[str, bytes] | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT mime, data FROM exercise_images WHERE exercise_id = ? AND kind = ?",
                (exercise_id, kind),
            ).fetchone()
            return (row["mime"], bytes(row["data"])) if row else None

    def list_image_keys(self) -> set[tuple[int, str]]:
        """사진이 저장된 (운동 id, 종류) 목록. 화면에서 사진 유무를 한 번에 판단할 때 쓴다."""
        with self._connect() as conn:
            return {(r["exercise_id"], r["kind"]) for r in conn.execute(
                "SELECT exercise_id, kind FROM exercise_images"
            )}

    # -------------------------------------------------------------- 즐겨찾기

    def list_favorites(self, body_part_id: int | None = None) -> list[Exercise]:
        """즐겨찾기 운동을 부위 순서 → 즐겨찾기 순서대로 반환한다."""
        sql = EXERCISE_SELECT + " JOIN favorites f ON f.exercise_id = e.id"
        params: tuple = ()
        if body_part_id is not None:
            sql += " WHERE e.body_part_id = ?"
            params = (body_part_id,)
        sql += " ORDER BY b.sort_order, f.sort_order"
        with self._connect() as conn:
            return [_to_exercise(r) for r in conn.execute(sql, params)]

    def is_favorite(self, exercise_id: int) -> bool:
        with self._connect() as conn:
            row = conn.execute("SELECT 1 FROM favorites WHERE exercise_id = ?", (exercise_id,))
            return row.fetchone() is not None

    def favorite_sort_order(self, exercise_id: int) -> int | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT sort_order FROM favorites WHERE exercise_id = ?", (exercise_id,)
            ).fetchone()
            return row["sort_order"] if row else None

    def add_favorite(self, exercise_id: int, sort_order: int | None = None) -> None:
        """즐겨찾기에 추가한다. sort_order를 주면 그 자리(삭제 되돌리기), 없으면 맨 뒤.
        이미 있으면 아무것도 하지 않는다.
        """
        with self._connect() as conn:
            if sort_order is None:
                conn.execute(
                    """INSERT INTO favorites (exercise_id, sort_order)
                       VALUES (?, (SELECT COALESCE(MAX(sort_order), -1) + 1 FROM favorites))
                       ON CONFLICT DO NOTHING""",
                    (exercise_id,),
                )
            else:
                conn.execute(
                    "INSERT INTO favorites (exercise_id, sort_order) VALUES (?, ?) ON CONFLICT DO NOTHING",
                    (exercise_id, sort_order),
                )

    def remove_favorite(self, exercise_id: int) -> None:
        with self._connect() as conn:
            conn.execute("DELETE FROM favorites WHERE exercise_id = ?", (exercise_id,))

    def move_favorite(self, exercise_id: int, direction: Literal[-1, 1]) -> None:
        """같은 부위 안에서 즐겨찾기 순서를 한 칸 위(-1) 또는 아래(+1)로 옮긴다."""
        if direction not in (-1, 1):
            raise ValueError("direction은 -1 또는 1이어야 합니다.")
        with self._connect() as conn:
            current = conn.execute(
                """SELECT f.id, f.sort_order, e.body_part_id
                   FROM favorites f JOIN exercises e ON e.id = f.exercise_id
                   WHERE f.exercise_id = ?""",
                (exercise_id,),
            ).fetchone()
            if current is None:
                return
            op, order = ("<", "DESC") if direction == -1 else (">", "ASC")
            neighbor = conn.execute(
                f"""SELECT f.id, f.sort_order
                    FROM favorites f JOIN exercises e ON e.id = f.exercise_id
                    WHERE e.body_part_id = ? AND f.sort_order {op} ?
                    ORDER BY f.sort_order {order} LIMIT 1""",
                (current["body_part_id"], current["sort_order"]),
            ).fetchone()
            if neighbor is None:
                return
            conn.execute(
                "UPDATE favorites SET sort_order = ? WHERE id = ?",
                (neighbor["sort_order"], current["id"]),
            )
            conn.execute(
                "UPDATE favorites SET sort_order = ? WHERE id = ?",
                (current["sort_order"], neighbor["id"]),
            )

    # -------------------------------------------------------------- 운동 기록

    def has_workout_on(self, workout_date: date) -> bool:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT 1 FROM workout_logs WHERE workout_date = ? LIMIT 1",
                (workout_date.isoformat(),),
            )
            return row.fetchone() is not None

    def save_workout(
        self,
        workout_date: date,
        exercise_ids: Iterable[int],
        *,
        mode: Literal["merge", "overwrite"] = "merge",
        memo: str = "",
    ) -> int:
        """하루치 운동을 저장하고 새로 추가된 기록 수를 반환한다.

        merge: 기존 기록은 두고 없는 운동만 추가한다.
        overwrite: 그 날짜의 기존 기록을 모두 지우고 다시 저장한다.
        """
        if mode not in ("merge", "overwrite"):
            raise ValueError("mode는 'merge' 또는 'overwrite'여야 합니다.")
        ids = list(dict.fromkeys(exercise_ids))
        if not ids:
            raise ValueError("저장할 운동을 하나 이상 선택해 주세요.")
        day = workout_date.isoformat()
        created_at = _now_text()
        added = 0
        with self._connect() as conn:
            if mode == "overwrite":
                conn.execute("DELETE FROM workout_logs WHERE workout_date = ?", (day,))
            for ex_id in ids:
                cur = conn.execute(
                    """INSERT INTO workout_logs (workout_date, exercise_id, memo, created_at)
                       VALUES (?, ?, ?, ?) ON CONFLICT DO NOTHING""",
                    (day, ex_id, memo, created_at),
                )
                added += cur.rowcount
        return added

    def list_workout_logs(
        self,
        start: date | None = None,
        end: date | None = None,
        body_part_ids: Iterable[int] | None = None,
    ) -> list[WorkoutLog]:
        """기간·부위로 필터링한 기록을 최신 날짜순으로 반환한다."""
        clauses: list[str] = []
        params: list = []
        if start is not None:
            clauses.append("l.workout_date >= ?")
            params.append(start.isoformat())
        if end is not None:
            clauses.append("l.workout_date <= ?")
            params.append(end.isoformat())
        if body_part_ids is not None:
            part_ids = list(body_part_ids)
            if not part_ids:
                return []
            clauses.append(f"b.id IN ({', '.join('?' * len(part_ids))})")
            params.extend(part_ids)
        sql = LOG_SELECT
        if clauses:
            sql += " WHERE " + " AND ".join(clauses)
        sql += " ORDER BY l.workout_date DESC, b.sort_order, l.id"
        with self._connect() as conn:
            return [_to_log(r) for r in conn.execute(sql, params)]

    def update_workout_log(
        self,
        log_id: int,
        *,
        workout_date: date | None = None,
        exercise_id: int | None = None,
        memo: str | None = None,
    ) -> None:
        fields: dict = {}
        if workout_date is not None:
            fields["workout_date"] = workout_date.isoformat()
        if exercise_id is not None:
            fields["exercise_id"] = exercise_id
        if memo is not None:
            fields["memo"] = memo
        if not fields:
            return
        assignments = ", ".join(f"{k} = ?" for k in fields)
        with self._connect() as conn:
            try:
                conn.execute(
                    f"UPDATE workout_logs SET {assignments} WHERE id = ?",
                    (*fields.values(), log_id),
                )
            except self.backend.integrity_error as e:
                if self.backend.is_unique_violation(e):
                    raise ValueError("그 날짜에 같은 운동 기록이 이미 있습니다.") from e
                raise ValueError("기록을 저장하지 못했어요. 입력값을 확인해 주세요.") from e

    def delete_workout_log(self, log_id: int) -> None:
        with self._connect() as conn:
            conn.execute("DELETE FROM workout_logs WHERE id = ?", (log_id,))

    def delete_workout_day(self, workout_date: date) -> None:
        with self._connect() as conn:
            conn.execute(
                "DELETE FROM workout_logs WHERE workout_date = ?", (workout_date.isoformat(),)
            )

    def last_workout_dates(self, until: date | None = None) -> dict[str, date | None]:
        """부위 이름 → 마지막 운동일. 기록이 없는 부위는 None.

        until(기본: 오늘) 이후의 기록은 제외한다. 잘못 입력한 미래 날짜가 "N일 후"로 표시되지 않게 한다.
        """
        until = until or clock.today()
        with self._connect() as conn:
            rows = conn.execute(
                """SELECT b.name, MAX(l.workout_date) AS last_date
                   FROM body_parts b
                   LEFT JOIN exercises e    ON e.body_part_id = b.id
                   LEFT JOIN workout_logs l ON l.exercise_id = e.id AND l.workout_date <= ?
                   GROUP BY b.id, b.name, b.sort_order
                   ORDER BY b.sort_order, b.id""",
                (until.isoformat(),),
            )
            return {
                r["name"]: date.fromisoformat(r["last_date"]) if r["last_date"] else None
                for r in rows
            }


# 하위 호환: 테스트와 기존 코드에서 SQLiteStorage(path)로 생성한다.
def SQLiteStorage(db_path: str | Path = DEFAULT_DB_PATH, seed_path: str | Path = SEED_PATH) -> Storage:
    return Storage(SQLiteBackend(db_path), seed_path)


def PostgresStorage(url: str, seed_path: str | Path = SEED_PATH) -> Storage:
    return Storage(PostgresBackend(url), seed_path)


def get_storage() -> Storage:
    """앱에서 사용할 저장소를 반환한다.

    DATABASE_URL이 있으면 PostgreSQL(Supabase), 없으면 SQLite를 쓴다.
    Streamlit은 secrets.toml의 최상위 문자열 값을 환경변수로도 내보내므로,
    Cloud의 Secrets에 DATABASE_URL을 넣으면 여기서 읽힌다 (app.py가 secrets를 먼저 읽는다).
    GYM_DB_PATH로 SQLite 파일 경로를 바꿀 수 있다 (테스트용 DB 분리 등).
    """
    url = os.environ.get("DATABASE_URL")
    if url:
        return _postgres_storage(url)
    return _sqlite_storage(str(os.environ.get("GYM_DB_PATH", DEFAULT_DB_PATH)))


@lru_cache
def _sqlite_storage(db_path: str) -> Storage:
    # 스키마 확인·시드 적재는 경로당 한 번만 실행되도록 인스턴스를 재사용한다.
    return SQLiteStorage(db_path)


@lru_cache
def _postgres_storage(url: str) -> Storage:
    # 연결 풀도 인스턴스와 함께 재사용된다.
    return PostgresStorage(url)
